/**
 * Strings for a document language: the exact tag, then its base language
 * (zh falls to zh-TW only through an explicit tag — a bare `zh` reads
 * English, as the site does not serve Simplified Chinese), else English.
 * @param {string | null | undefined} lang
 * @returns {{ lang: string, messages: Readonly<ConsentMessages> }}
 */
export function consentMessagesFor(lang) {
  const tag = typeof lang === 'string' ? lang.trim() : '';
  const exact = Object.keys(CONSENT_MESSAGES).find((key) => key.toLowerCase() === tag.toLowerCase());
  if (exact) return { lang: exact, messages: CONSENT_MESSAGES[exact] };
  const base = tag.split('-')[0].toLowerCase();
  if (base && base !== 'zh' && CONSENT_MESSAGES[base]) return { lang: base, messages: CONSENT_MESSAGES[base] };
  return { lang: 'en', messages: CONSENT_MESSAGES.en };
}
